import csv
from pathlib import Path

from mock_statements import LEVELS, TRANSACTIONS, build_all
from monolith import run_monolith

RUNS_PER_LEVEL = 5
RESULTS_CSV = Path(__file__).parent / "results" / "complexity_results.csv"
RESULTS_MD = Path(__file__).parent / "results" / "complexity_results.md"


def _safe_amount(value):
    try:
        return round(float(value), 2)
    except (TypeError, ValueError):
        return None


def _score_run(extracted: list) -> dict:
    """Compare extracted transactions to the fixed 10-transaction ground
    truth by matching on (date, amount). Description phrasing and row
    order don't matter, only whether the right date/amount pairs were
    found, and whether anything extra or malformed showed up.
    """
    ground_truth = {(t["date"], round(t["amount"], 2)) for t in TRANSACTIONS}
    found = set()
    hallucinated = 0

    for row in extracted:
        amount = _safe_amount(row.get("amount"))
        key = (row.get("date"), amount)
        if amount is None or key not in ground_truth:
            hallucinated += 1
        else:
            found.add(key)

    return {
        "extracted_count": len(extracted),
        "matched_count": len(found),
        "missed_count": len(ground_truth) - len(found),
        "hallucinated_count": hallucinated,
    }


def _signature(extracted: list) -> str:
    """A stable fingerprint of which (date, amount) pairs came back,
    used to check whether repeated runs on the same input agree.
    """
    pairs = sorted(
        (row.get("date"), _safe_amount(row.get("amount")))
        for row in extracted
    )
    return str(pairs)


def main():
    RESULTS_CSV.parent.mkdir(parents=True, exist_ok=True)
    pdf_paths = build_all()

    fieldnames = [
        "level", "level_name", "run", "valid_json",
        "extracted_count", "matched_count", "missed_count", "hallucinated_count",
        "signature",
    ]
    rows = []

    for level, (level_name, _) in LEVELS.items():
        pdf_path = pdf_paths[level]
        print(f"\n=== Level {level}: {level_name} ({pdf_path.name}) ===")

        for run in range(1, RUNS_PER_LEVEL + 1):
            result = run_monolith(pdf_path)
            if result["valid_json"]:
                score = _score_run(result["transactions"])
                signature = _signature(result["transactions"])
            else:
                score = {
                    "extracted_count": 0, "matched_count": 0,
                    "missed_count": len(TRANSACTIONS), "hallucinated_count": 0,
                }
                signature = None

            row = {
                "level": level, "level_name": level_name, "run": run,
                "valid_json": result["valid_json"], **score,
                "signature": signature,
            }
            rows.append(row)
            print(f"  Run {run}: valid_json={result['valid_json']} "
                  f"matched={score['matched_count']}/{len(TRANSACTIONS)} "
                  f"hallucinated={score['hallucinated_count']}")

    with open(RESULTS_CSV, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    _write_markdown_summary(rows)
    print(f"\nSaved {RESULTS_CSV} and {RESULTS_MD}")


def _write_markdown_summary(rows: list):
    by_level = {}
    for row in rows:
        by_level.setdefault(row["level"], []).append(row)

    lines = [
        "# Monolith Complexity Results",
        "",
        "Generated by `run_complexity_experiment.py`. Each level holds the same "
        f"{len(TRANSACTIONS)} transactions constant and only changes layout complexity. "
        f"{RUNS_PER_LEVEL} independent runs per level, same PDF, same prompt, temperature 0.7.",
        "",
        "| Level | Description | Valid JSON rate | Avg matched / 10 | Avg hallucinated | Identical across runs? |",
        "|---|---|---|---|---|---|",
    ]

    for level, (level_name, _) in LEVELS.items():
        level_rows = by_level.get(level, [])
        n = len(level_rows) or 1
        valid_rate = sum(r["valid_json"] for r in level_rows) / n
        avg_matched = sum(r["matched_count"] for r in level_rows) / n
        avg_hallucinated = sum(r["hallucinated_count"] for r in level_rows) / n
        signatures = {r["signature"] for r in level_rows if r["valid_json"]}
        if len(signatures) == 0:
            identical = "N/A (no valid runs)"
        elif len(signatures) == 1:
            identical = "Yes"
        else:
            identical = f"No ({len(signatures)} distinct outputs)"
        lines.append(
            f"| {level} | {level_name} | {valid_rate:.0%} | {avg_matched:.1f} | "
            f"{avg_hallucinated:.1f} | {identical} |"
        )

    RESULTS_MD.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
